const queue: string[] = [];
let showing = false;

/** Этому учит пролог — отдельная подсказка не нужна. */
const TAUGHT_BY_PROLOGUE = ['settle', 'battle', 'upgrade', 'points', 'quest'];

export function hint(state: GameState, id: keyof typeof HINTS) {
  const seen = (state.hints ??= []);
  if (seen.includes(id) || queue.includes(id)) return;
  if (prologueActive(state) && TAUGHT_BY_PROLOGUE.includes(id)) {
    seen.push(id);
    return;
  }
  queue.push(id);
  next(state);
}

function next(state: GameState) {
  if (showing || !queue.length) return;
  // Не мешаем окнам и бою: ждём, пока они закроются
  if (uiRoot().querySelector('.modal-back, .battle-ui, .menu')) {
    setTimeout(() => next(state), 1200);
    return;
  }
  const id = queue.shift()!;
  (state.hints ??= []).push(id);
  const hd = HINTS[id];
  showing = true;
  const card = h(
    'div',
    { class: 'hint-card' },
    h('div', { class: 'row', style: 'justify-content:space-between;gap:8px' }, h('b', { class: 'gold' }, tr`Совет · ${hd.title}`), btn(tr('Понятно'), () => {
      card.remove();
      showing = false;
      setTimeout(() => next(state), 400);
    }, 'small')),
    h('div', { style: 'font-size:13px;line-height:1.35' }, hd.text),
  );
  uiRoot().append(card);
}

export function resetHints() {
  queue.length = 0;
  showing = false;
  uiRoot().querySelectorAll('.hint-card').forEach((e) => e.remove());
}

