const queue: string[] = [];
let showing = false;

export function hint(state: GameState, id: keyof typeof HINTS) {
  const seen = (state.hints ??= []);
  if (seen.includes(id) || queue.includes(id)) return;
  queue.push(id);
  next(state);
}

function next(state: GameState) {
  if (showing || !queue.length) return;
  // Не мешаем окнам и бою: ждём, пока они закроются
  if (uiRoot().querySelector('.modal-back, .battle-ui, .menu')) {
    setTimeout(() => next(state), 1200);
    return;
  }
  const id = queue.shift()!;
  (state.hints ??= []).push(id);
  const hd = HINTS[id];
  showing = true;
  const card = h(
    'div',
    { class: 'hint-card' },
    h('div', { class: 'row', style: 'justify-content:space-between;gap:8px' }, h('b', { class: 'gold' }, `Совет · ${hd.title}`), btn('Понятно', () => {
      card.remove();
      showing = false;
      setTimeout(() => next(state), 400);
    }, 'small')),
    h('div', { style: 'font-size:13px;line-height:1.35' }, hd.text),
  );
  uiRoot().append(card);
}

export function resetHints() {
  queue.length = 0;
  showing = false;
  uiRoot().querySelectorAll('.hint-card').forEach((e) => e.remove());
}

