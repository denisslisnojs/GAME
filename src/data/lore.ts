/** Короткий рассказ лорда о себе. */
export function lordBio(title: string, name: string, home: string, rank: number, seed: number): string {
  const trait = TRAITS[Math.abs(seed) % TRAITS.length];
  const role = rank === 3 ? 'Я правлю этой державой, как правили мои предки.' : rank === 2 ? `Я держу ${home} и земли вокруг именем государя.` : `Мой род служит государю мечом, а мне вверен ${home}.`;
  return `«${title} ${name}. ${role}» ${trait}`;
}

