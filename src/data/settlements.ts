function build(): SettlementDef[] {
  const out: SettlementDef[] = [];
  for (const culture of Object.keys(TOWNS) as FactionId[]) {
    for (const [id, name, lon, lat, goods, about] of TOWNS[culture]) {
      out.push({ id, name, type: 'town', culture, lon, lat, goods, about });
    }
    for (const [id, name, lon, lat, goods, about] of CASTLES[culture]) {
      out.push({ id, name, type: 'castle', culture, lon, lat, goods, about });
    }
  }
  return out;
}

